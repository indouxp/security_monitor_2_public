#!/bin/bash
################################################################################
# 概要        : push_metrics.sh 単体テスト共通ライブラリ
#               各テストケース TC-NNN.sh から source して使用する。
#               - モックファイル(/proc・/sys 相当)の生成
#               - モック受信サーバー(mock_recv.py)の起動・停止
#               - 試験対象スクリプトのモック環境での実行
#               - 確認事項の判定・記録（check / check_eq）
#               - 全出力のログ採取とエラー時 0 以外終了（run_tc）
# Created     : 2026-05-21
# Author      : Tsystem
################################################################################
set -uo pipefail
# -u          : 未定義変数の参照をエラー扱い
# -o pipefail : パイプ内のいずれかが失敗したらエラー扱い
# ※ -e は付けない。確認事項が FAIL してもテストを継続するため。

UT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)            # ut/push_metrics.sh/
readonly UT_DIR
readonly SCRIPT="${UT_DIR}/../../inventory/client/lin/push_metrics.sh"  # 試験対象
readonly WORK="${UT_DIR}/work"                                  # 作業ディレクトリ
readonly MOCK="${WORK}/mock"                                    # モックファイル配置先
readonly HIST="${WORK}/hist"                                    # 履歴・ログ保存先(HISTORY_DIR)
readonly HISTORY_FILE="${HIST}/history.ndjson"                  # ローカル履歴ファイル
readonly POST_LOG="${HIST}/push_metrics.log"                    # スクリプトのエラーログ
readonly RECV_PORT=19092                                        # モック受信サーバーの待受ポート
readonly RECV_FILE="${WORK}/received.json"                      # モック受信サーバーが保存するPOSTボディ

# ---- 試験結果（check 系で蓄積） ----
_pass=0                                                         # PASS した確認事項数
_fail=0                                                         # FAIL した確認事項数
_fail_desc=()                                                   # FAIL した確認事項の説明
_recv_pid=""                                                    # モック受信サーバーのプロセスID

################################################################################
# ログ
#-------------------------------------------------------------------------------
# 概要     : タイムスタンプ付きでメッセージを標準出力に書き出す
# 引数     : $1 - 出力するメッセージ文字列
#-------------------------------------------------------------------------------
log() { echo "$(date '+%Y%m%d.%H%M%S'): $1"; }

################################################################################
# モックファイル生成
#-------------------------------------------------------------------------------
# 概要     : モック環境を初期化し、全メトリクスの既定正常値を用意する。
#            各 TC は検証対象のモックのみ上書きすればよい。
# 引数     : なし
#-------------------------------------------------------------------------------
setup_mock() {
    rm -rf "$MOCK" "$HIST"
    mkdir -p "$MOCK" "$HIST"
    write_stat 1 100 0 50 800 50 0 0 0          # CPU統計 1回目サンプル
    write_stat 2 110 0 55 820 55 0 0 0          # CPU統計 2回目サンプル
    write_diskstat 1 sda 1000 2000              # ディスク統計 1回目サンプル
    write_diskstat 2 sda 1000 2000              # ディスク統計 2回目サンプル
    write_thermal 0 45000                       # thermal_zone 温度 45.0℃
    write_meminfo 4000000 1000000               # メモリ 総4GB / 空き1GB
}

#-------------------------------------------------------------------------------
# 概要     : /proc/stat モック(cpu行)を書き出す
# 引数     : $1 サンプル番号(1 or 2)  $2.. cpu行の数値(user nice system idle iowait ...)
#-------------------------------------------------------------------------------
write_stat() {
    local n=$1; shift                                          # サンプル番号
    echo "cpu $*" > "${MOCK}/stat${n}"
}

#-------------------------------------------------------------------------------
# 概要     : /proc/diskstats モックを1デバイスで書き出す（上書き）
# 引数     : $1 サンプル番号  $2 デバイス名  $3 累積読込セクタ  $4 累積書込セクタ
# 補足     : diskstats 形式は $3=デバイス名 $6=読込セクタ $10=書込セクタ、計14フィールド
#-------------------------------------------------------------------------------
write_diskstat() {
    local n=$1 dev=$2 rd=$3 wr=$4                               # サンプル番号・デバイス名・読込/書込セクタ
    printf '8 0 %s 0 0 %s 0 0 0 %s 0 0 0 0\n' "$dev" "$rd" "$wr" > "${MOCK}/diskstats${n}"
}

#-------------------------------------------------------------------------------
# 概要     : /proc/diskstats モックにデバイス行を追記する
# 引数     : $1 サンプル番号  $2 デバイス名  $3 累積読込セクタ  $4 累積書込セクタ
#-------------------------------------------------------------------------------
add_diskstat() {
    local n=$1 dev=$2 rd=$3 wr=$4                               # サンプル番号・デバイス名・読込/書込セクタ
    printf '8 0 %s 0 0 %s 0 0 0 %s 0 0 0 0\n' "$dev" "$rd" "$wr" >> "${MOCK}/diskstats${n}"
}

#-------------------------------------------------------------------------------
# 概要     : thermal_zone 温度センサーモックを作成する
# 引数     : $1 ゾーン番号  $2 温度(milli-celsius)
#-------------------------------------------------------------------------------
write_thermal() {
    local zone=$1 milli=$2                                      # ゾーン番号・温度(milli-celsius)
    mkdir -p "${MOCK}/thermal/thermal_zone${zone}"
    echo "$milli" > "${MOCK}/thermal/thermal_zone${zone}/temp"
}

#-------------------------------------------------------------------------------
# 概要     : hwmon 温度センサーモックを作成する
# 引数     : $1 hwmonインデックス  $2 センサー番号  $3 温度(milli-celsius)
#-------------------------------------------------------------------------------
write_hwmon() {
    local idx=$1 sensor=$2 milli=$3                             # hwmon番号・センサー番号・温度(milli-celsius)
    mkdir -p "${MOCK}/hwmon/hwmon${idx}"
    echo "$milli" > "${MOCK}/hwmon/hwmon${idx}/temp${sensor}_input"
}

#-------------------------------------------------------------------------------
# 概要     : 温度センサーモック(thermal_zone・hwmon)を全削除する
# 引数     : なし
#-------------------------------------------------------------------------------
clear_thermal() {
    rm -rf "${MOCK}/thermal" "${MOCK}/hwmon"
}

#-------------------------------------------------------------------------------
# 概要     : /proc/meminfo モックを書き出す
# 引数     : $1 MemTotal(KB)  $2 MemAvailable(KB)
#-------------------------------------------------------------------------------
write_meminfo() {
    {
        echo "MemTotal:       $1 kB"
        echo "MemFree:        12345 kB"
        echo "MemAvailable:   $2 kB"
    } > "${MOCK}/meminfo"
}

################################################################################
# モック受信サーバー
#-------------------------------------------------------------------------------
# 概要     : モック受信サーバー mock_recv.py を起動し、待受開始まで待機する
# 引数     : なし
# 戻り値   : 起動成功で 0、失敗で 1
#-------------------------------------------------------------------------------
start_recv() {
    rm -f "$RECV_FILE"
    # env 経由で渡す（RECV_FILE は readonly のためコマンド前置代入は使えない）
    env MOCK_PORT="$RECV_PORT" RECV_FILE="$RECV_FILE" \
        python3 "${UT_DIR}/mock_recv.py" &
    _recv_pid=$!
    local i                                                    # 待機リトライ回数
    for i in $(seq 1 50); do
        if (: < "/dev/tcp/127.0.0.1/${RECV_PORT}") 2>/dev/null; then
            return 0
        fi
        sleep 0.1
    done
    echo "  ERROR: モック受信サーバーが起動しません (port ${RECV_PORT})"
    return 1
}

#-------------------------------------------------------------------------------
# 概要     : モック受信サーバーを停止する
# 引数     : なし
#-------------------------------------------------------------------------------
stop_recv() {
    [[ -n "$_recv_pid" ]] || return 0
    kill "$_recv_pid" 2>/dev/null
    wait "$_recv_pid" 2>/dev/null
    _recv_pid=""
}

################################################################################
# 試験対象の実行
#-------------------------------------------------------------------------------
# 概要     : モック環境で push_metrics.sh を1回実行する。
# 引数     : $@ - 追加の環境変数(KEY=VAL 形式。後勝ちで既定値を上書きする)
# 補足     : ENDPOINT 既定は到達不能URL(即座に接続拒否)。POST試験では TC が上書きする。
# 戻り値   : push_metrics.sh の終了コード
#-------------------------------------------------------------------------------
run_script() {
    env HISTORY_DIR="$HIST" \
        SAMPLE_DELAY=0 \
        ENDPOINT="http://127.0.0.1:1/" \
        PROC_STAT="${MOCK}/stat1" \
        PROC_STAT_2="${MOCK}/stat2" \
        PROC_DISKSTATS="${MOCK}/diskstats1" \
        PROC_DISKSTATS_2="${MOCK}/diskstats2" \
        PROC_MEMINFO="${MOCK}/meminfo" \
        THERMAL_GLOB="${MOCK}/thermal/thermal_zone*/temp" \
        HWMON_GLOB="${MOCK}/hwmon/hwmon*/temp*_input" \
        "$@" \
        bash "$SCRIPT"
}

################################################################################
# 出力ファイルの参照
#-------------------------------------------------------------------------------
# 概要     : 1行JSONファイルから指定キーの値を取り出す（内部関数）
# 引数     : $1 対象ファイル  $2 JSONキー名
# 出力     : キーの値（文字列値は前後のダブルクオートを除去）
#-------------------------------------------------------------------------------
_extract() {
    local file=$1 key=$2 raw                                   # 対象ファイル・キー名・抽出文字列
    raw=$(grep -oE "\"${key}\":[^,}]*" "$file" 2>/dev/null | head -1)
    raw=${raw#\"${key}\":}                                      # 「"キー":」部分を除去
    raw=${raw#\"}; raw=${raw%\"}                                # 文字列値の前後ダブルクオートを除去
    printf '%s' "$raw"
}

#-------------------------------------------------------------------------------
# 概要     : ローカル履歴ファイルから指定キーの値を取り出す
# 引数     : $1 - JSONキー名
#-------------------------------------------------------------------------------
hist_field() { _extract "$HISTORY_FILE" "$1"; }

#-------------------------------------------------------------------------------
# 概要     : モック受信サーバーが保存したPOSTボディから指定キーの値を取り出す
# 引数     : $1 - JSONキー名
#-------------------------------------------------------------------------------
recv_field() { _extract "$RECV_FILE" "$1"; }

#-------------------------------------------------------------------------------
# 概要     : ローカル履歴ファイルに指定キーが存在するか判定する
# 引数     : $1 - JSONキー名
# 戻り値   : 存在すれば 0、なければ 1
#-------------------------------------------------------------------------------
hist_has_key() {
    grep -q "\"$1\":" "$HISTORY_FILE" 2>/dev/null
}

#-------------------------------------------------------------------------------
# 概要     : モック受信サーバーが保存したPOSTボディに指定キーが存在するか判定する
# 引数     : $1 - JSONキー名
# 戻り値   : 存在すれば 0、なければ 1
#-------------------------------------------------------------------------------
recv_has_key() {
    grep -q "\"$1\":" "$RECV_FILE" 2>/dev/null
}

#-------------------------------------------------------------------------------
# 概要     : ローカル履歴ファイルの行数を出力する
# 引数     : なし
# 出力     : 行数（ファイルがなければ 0）
#-------------------------------------------------------------------------------
hist_lines() {
    if [[ -f "$HISTORY_FILE" ]]; then wc -l < "$HISTORY_FILE"; else echo 0; fi
}

#-------------------------------------------------------------------------------
# 概要     : スクリプトのエラーログに指定パターンが含まれるか判定する
# 引数     : $1 - 検索パターン(grep -E)
# 戻り値   : 含まれれば 0、なければ 1
#-------------------------------------------------------------------------------
log_has() {
    grep -qE "$1" "$POST_LOG" 2>/dev/null
}

################################################################################
# 確認事項の判定
#-------------------------------------------------------------------------------
# 概要     : 期待値と実際値を比較し、結果(PASS/FAIL)を記録・表示する
# 引数     : $1 確認事項の説明  $2 実際値  $3 期待値
#-------------------------------------------------------------------------------
check_eq() {
    local desc=$1 actual=$2 expected=$3                         # 説明・実際値・期待値
    if [[ "$actual" == "$expected" ]]; then
        echo "  PASS: ${desc}"
        _pass=$((_pass + 1))
    else
        echo "  FAIL: ${desc} (期待=${expected} / 実際=${actual})"
        _fail=$((_fail + 1))
        _fail_desc+=("$desc")
    fi
}

#-------------------------------------------------------------------------------
# 概要     : 終了ステータスで結果(PASS/FAIL)を記録・表示する
# 引数     : $1 確認事項の説明  $2 終了ステータス(0=成功)
#-------------------------------------------------------------------------------
check() {
    local desc=$1 status=$2                                     # 説明・終了ステータス
    if [[ "$status" -eq 0 ]]; then
        echo "  PASS: ${desc}"
        _pass=$((_pass + 1))
    else
        echo "  FAIL: ${desc}"
        _fail=$((_fail + 1))
        _fail_desc+=("$desc")
    fi
}

################################################################################
# テストケース実行
#-------------------------------------------------------------------------------
# 概要     : テストケース本体を実行し、全出力をログ採取して結果を集計する。
#            確認事項に1件でも FAIL があれば終了コード 1 で終了する。
# 引数     : $1 テスト本体の関数名  $2 当該TCのファイルパス($0)  $3 テスト概要
#-------------------------------------------------------------------------------
run_tc() {
    local func=$1 file=$2 desc=$3                               # 関数名・ファイルパス・概要
    local name logf                                             # TC名・ログパス
    name=$(basename "$file")
    logf="${file}.log"

    exec 3>&1 4>&2                                              # 元の標準出力・標準エラーを退避
    exec > >(tee "$logf") 2>&1                                  # 全出力をログと画面の両方へ

    log "START ${name}: ${desc}"
    "$func"                                                     # テスト本体を実行
    stop_recv                                                   # モック受信サーバーが残っていれば停止
    log "結果: PASS=${_pass}件 FAIL=${_fail}件"
    (( _fail > 0 )) && log "失敗確認事項: ${_fail_desc[*]}"
    log "END ${name}"

    exec 1>&3 2>&4                                              # FDを復元（tee へEOF送出→flush）
    exec 3>&- 4>&-

    (( _fail == 0 ))                                            # FAIL があれば非ゼロ終了
}
