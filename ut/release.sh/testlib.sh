#!/bin/bash
################################################################################
# 概要        : release.sh 単体テスト共通ライブラリ
#               各テストケース TC-NNN.sh から source して使用する。
#               - ローカルファイル・モックリモートFS・release.txt の生成
#               - フェイク ssh/scp を PATH 注入し、expect 経由で release.sh を実行
#               - 確認事項の判定・記録（check / check_eq）
#               - 全出力のログ採取とエラー時 0 以外終了（run_tc）
# Created     : 2026-05-21
# Author      : Tsystem
################################################################################
set -uo pipefail
# -u          : 未定義変数の参照をエラー扱い
# -o pipefail : パイプ内のいずれかが失敗したらエラー扱い
# ※ -e は付けない。確認事項が FAIL してもテストを継続するため。

UT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)            # ut/release.sh/
readonly UT_DIR
readonly SCRIPT="${UT_DIR}/../../inventory/release.sh"          # 試験対象
readonly BIN="${UT_DIR}/bin"                                    # フェイク ssh/scp の配置先
readonly WORK="${UT_DIR}/work"                                  # 作業ディレクトリ
readonly LOCAL="${WORK}/local"                                  # リリース元ローカルファイル置き場
readonly REMOTE_ROOT="${WORK}/remote"                           # モックリモートFSのルート
readonly LIST="${WORK}/release.txt"                             # release.txt（リリースリスト）
readonly CALL_LOG="${WORK}/calls.log"                           # フェイク ssh/scp の呼び出し記録
readonly OUT="${WORK}/out.txt"                                  # release.sh の出力キャプチャ

# フェイク ssh/scp が参照する変数は環境へ輸出する（readonly でも export 属性は付与可）。
# run_release のコマンド前置代入では readonly 変数を代入できないため export で渡す。
export REMOTE_ROOT CALL_LOG

# ---- 試験結果（check 系で蓄積） ----
_pass=0                                                         # PASS した確認事項数
_fail=0                                                         # FAIL した確認事項数
_fail_desc=()                                                   # FAIL した確認事項の説明

################################################################################
# ログ
#-------------------------------------------------------------------------------
# 概要     : タイムスタンプ付きでメッセージを標準出力に書き出す
# 引数     : $1 - 出力するメッセージ文字列
#-------------------------------------------------------------------------------
log() { echo "$(date '+%Y%m%d.%H%M%S'): $1"; }

################################################################################
# モック環境の生成
#-------------------------------------------------------------------------------
# 概要     : 作業ディレクトリを作り直し、ローカル・リモートの土台を用意する
# 引数     : なし
#-------------------------------------------------------------------------------
setup() {
    rm -rf "$WORK"
    mkdir -p "$LOCAL" "$REMOTE_ROOT"
}

#-------------------------------------------------------------------------------
# 概要     : リリース元のローカルファイルを作成する
# 引数     : $1 ファイル名（LOCAL 配下）  $2 内容
#-------------------------------------------------------------------------------
write_local() {
    printf '%s\n' "$2" > "${LOCAL}/$1"
}

#-------------------------------------------------------------------------------
# 概要     : モックリモートFS上にファイルを作成する
# 引数     : $1 リモート絶対パス  $2 内容
#-------------------------------------------------------------------------------
write_remote() {
    local real="${REMOTE_ROOT}$1"                              # モックリモートFS上の実体パス
    mkdir -p "$(dirname "$real")"
    printf '%s\n' "$2" > "$real"
}

#-------------------------------------------------------------------------------
# 概要     : release.txt（リリースリスト）を生成する
# 引数     : $@ - 各行の文字列
#-------------------------------------------------------------------------------
write_list() {
    : > "$LIST"
    local ln                                                   # 1行分の文字列
    for ln in "$@"; do
        printf '%s\n' "$ln" >> "$LIST"
    done
}

################################################################################
# 試験対象の実行
#-------------------------------------------------------------------------------
# 概要     : フェイク ssh/scp を PATH 注入し、expect 経由で release.sh を実行する。
# 引数     : $1   confirm() への回答列（空白区切りの S/Y/C。プロンプト無しなら ""）
#            $2.. release.sh へ渡す引数（-c <list> user@host 等）
# 補足     : CWD を LOCAL にして実行する（release.txt のスラッシュ無しローカルパスが
#            ./ 付与で LOCAL 配下に解決されるようにするため）。
# 戻り値   : release.sh の終了コード
#-------------------------------------------------------------------------------
run_release() {
    local answers=$1; shift                                    # confirm 回答列
    : > "$CALL_LOG"
    (
        cd "$LOCAL" || exit 1
        # REMOTE_ROOT・CALL_LOG は export 済み。PATH・LOG_DIR のみ前置代入で渡す。
        PATH="${BIN}:${PATH}" \
        LOG_DIR="$WORK" \
        expect "${UT_DIR}/drive.exp" "$SCRIPT" "$answers" "$@"
    ) > "$OUT" 2>&1
    return $?
}

################################################################################
# 出力・結果の参照
#-------------------------------------------------------------------------------
# 概要     : release.sh の出力に指定文字列(固定)が含まれるか判定する
# 引数     : $1 - 検索文字列
# 戻り値   : 含まれれば 0
#-------------------------------------------------------------------------------
out_has() {
    grep -qF "$1" "$OUT" 2>/dev/null
}

#-------------------------------------------------------------------------------
# 概要     : フェイク ssh/scp の呼び出し記録に指定パターンが含まれるか判定する
# 引数     : $1 - 検索パターン(grep -E)
# 戻り値   : 含まれれば 0
#-------------------------------------------------------------------------------
calls_has() {
    grep -qE "$1" "$CALL_LOG" 2>/dev/null
}

#-------------------------------------------------------------------------------
# 概要     : モックリモートFS上のファイル内容を出力する
# 引数     : $1 - リモート絶対パス
#-------------------------------------------------------------------------------
remote_content() {
    cat "${REMOTE_ROOT}$1" 2>/dev/null
}

#-------------------------------------------------------------------------------
# 概要     : モックリモートFS上にファイルが存在するか判定する
# 引数     : $1 - リモート絶対パス
# 戻り値   : 存在すれば 0
#-------------------------------------------------------------------------------
remote_exists() {
    [[ -f "${REMOTE_ROOT}$1" ]]
}

################################################################################
# 確認事項の判定
#-------------------------------------------------------------------------------
# 概要     : 期待値と実際値を比較し、結果(PASS/FAIL)を記録・表示する
# 引数     : $1 確認事項の説明  $2 実際値  $3 期待値
#-------------------------------------------------------------------------------
check_eq() {
    local desc=$1 actual=$2 expected=$3                         # 説明・実際値・期待値
    if [[ "$actual" == "$expected" ]]; then
        echo "  PASS: ${desc}"
        _pass=$((_pass + 1))
    else
        echo "  FAIL: ${desc} (期待=${expected} / 実際=${actual})"
        _fail=$((_fail + 1))
        _fail_desc+=("$desc")
    fi
}

#-------------------------------------------------------------------------------
# 概要     : 終了ステータスで結果(PASS/FAIL)を記録・表示する
# 引数     : $1 確認事項の説明  $2 終了ステータス(0=成功)
#-------------------------------------------------------------------------------
check() {
    local desc=$1 status=$2                                     # 説明・終了ステータス
    if [[ "$status" -eq 0 ]]; then
        echo "  PASS: ${desc}"
        _pass=$((_pass + 1))
    else
        echo "  FAIL: ${desc}"
        _fail=$((_fail + 1))
        _fail_desc+=("$desc")
    fi
}

################################################################################
# テストケース実行
#-------------------------------------------------------------------------------
# 概要     : テストケース本体を実行し、全出力をログ採取して結果を集計する。
#            確認事項に1件でも FAIL があれば終了コード 1 で終了する。
# 引数     : $1 テスト本体の関数名  $2 当該TCのファイルパス($0)  $3 テスト概要
#-------------------------------------------------------------------------------
run_tc() {
    local func=$1 file=$2 desc=$3                               # 関数名・ファイルパス・概要
    local name logf                                             # TC名・ログパス
    name=$(basename "$file")
    logf="${file}.log"

    exec 3>&1 4>&2                                              # 元の標準出力・標準エラーを退避
    exec > >(tee "$logf") 2>&1                                  # 全出力をログと画面の両方へ

    log "START ${name}: ${desc}"
    "$func"                                                     # テスト本体を実行
    log "結果: PASS=${_pass}件 FAIL=${_fail}件"
    (( _fail > 0 )) && log "失敗確認事項: ${_fail_desc[*]}"
    log "END ${name}"

    exec 1>&3 2>&4                                              # FDを復元（tee へEOF送出→flush）
    exec 3>&- 4>&-

    (( _fail == 0 ))                                            # FAIL があれば非ゼロ終了
}
